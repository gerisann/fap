// Copies the word lists from web/src/profanity.js into firestore.rules (between the BEGIN/END markers),
// so the client check and the real gate never drift apart. Run: npm run sync:profanity
import { readFileSync, writeFileSync } from "node:fs";
import { STEMS, WORDS, NAME_STEMS } from "../web/src/profanity.js";

const RULES = new URL("../firestore.rules", import.meta.url);
const ascii = list => { for (const w of list) if (!/^[a-z0-9 ]+$/.test(w)) throw new Error("not folded ASCII: " + w); return list.join("|"); };

const block = `    // BEGIN profanity (generated by npm run sync:profanity from web/src/profanity.js – do not edit by hand)
    function fold(s) {
      return s.lower().replace('0', 'o').replace('[1!|]', 'i').replace('3', 'e').replace('[4@]', 'a').replace('[5$]', 's').replace('7', 't')
        .replace('[áàâäãÁÀÂÄÃ]', 'a').replace('[éèêëÉÈÊË]', 'e').replace('[íìîïÍÌÎÏ]', 'i').replace('[óòôöőõÓÒÔÖŐÕ]', 'o')
        .replace('[úùûüűÚÙÛÜŰ]', 'u').replace('[ñÑ]', 'n').replace('[çÇ]', 'c');
    }
    function badText(s) {
      let f = fold(s);
      return f.matches('(?s)(.*[^a-z])?(${ascii(STEMS)}).*')
        || f.matches('(?s)(.*[^a-z])?(${ascii(WORDS)})([^a-z].*)?');
    }
    function badName(s) {
      return fold(s).replace('[_-]', '').matches('.*(${ascii(NAME_STEMS)}).*');
    }
    // END profanity`;

const src = readFileSync(RULES, "utf8");
const re = /    \/\/ BEGIN profanity[\s\S]*?\/\/ END profanity/;
if (!re.test(src)) throw new Error("markers not found in firestore.rules");
writeFileSync(RULES, src.replace(re, block));
console.log(`firestore.rules: ${STEMS.length} stems, ${WORDS.length} whole words, ${NAME_STEMS.length} name stems`);
