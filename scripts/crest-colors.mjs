// Main colour of every crest in web/public/logos/ -> web/src/data/crest-colors.js ({ apiId: "#rrggbb" }).
// The map, donuts and tribe badges use it for API teams (the curated colour in teams.js still wins).
// No image library: our crests are 8-bit RGBA PNGs (fetch-logos writes PNG32), decoded with zlib here.
// Run: node scripts/crest-colors.mjs (fetch-logos.mjs runs it too)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { inflateSync } from "node:zlib";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const DIR = "web/public/logos";

// RGBA pixels of a non-interlaced 8-bit RGBA PNG, or null for anything else
export function decodePng(buf) {
  if (buf.readUInt32BE(0) !== 0x89504e47) return null;
  let o = 8, w = 0, h = 0; const idat = [];
  while (o < buf.length) {
    const len = buf.readUInt32BE(o), type = buf.toString("ascii", o + 4, o + 8), d = buf.subarray(o + 8, o + 8 + len);
    if (type === "IHDR") { w = d.readUInt32BE(0); h = d.readUInt32BE(4); if (d[8] !== 8 || d[9] !== 6 || d[12] !== 0) return null; }
    else if (type === "IDAT") idat.push(d);
    else if (type === "IEND") break;
    o += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat)), bpp = 4, stride = w * bpp, px = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)], src = y * (stride + 1) + 1, dst = y * stride;
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? px[dst + x - bpp] : 0, b = y ? px[dst - stride + x] : 0, c = x >= bpp && y ? px[dst - stride + x - bpp] : 0;
      let v = raw[src + x];
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      px[dst + x] = v & 255;
    }
  }
  return { w, h, px };
}

// the biggest group of saturated colour; a black-and-white crest gets a light grey (a dark dot would vanish on the dark map)
export function mainColor({ px }) {
  const buckets = new Map(); let opaque = 0, colourful = 0;
  for (let i = 0; i < px.length; i += 4) {
    const r = px[i], g = px[i + 1], b = px[i + 2], a = px[i + 3];
    if (a < 200) continue; opaque++;
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
    if (mx < 50 || (mx - mn) / mx < 0.35) continue; // black, white, grey
    colourful++;
    const k = (r >> 5) << 6 | (g >> 5) << 3 | (b >> 5), e = buckets.get(k) || [0, 0, 0, 0];
    e[0]++; e[1] += r; e[2] += g; e[3] += b; buckets.set(k, e);
  }
  if (!opaque || colourful < opaque * 0.12) return "#dedede";
  const [n, r, g, b] = [...buckets.values()].sort((x, y) => y[0] - x[0])[0];
  return "#" + [r, g, b].map(v => Math.round(v / n).toString(16).padStart(2, "0")).join("");
}

export function writeCrestColors() {
  const out = {};
  for (const f of readdirSync(DIR)) {
    const id = parseInt(f); if (!Number.isInteger(id)) continue;
    const img = decodePng(readFileSync(join(DIR, f)));
    if (img) out[id] = mainColor(img);
  }
  const ids = Object.keys(out).sort((a, b) => a - b);
  writeFileSync("web/src/data/crest-colors.js",
    "// Generated by scripts/crest-colors.mjs: main colour of each crest (API-Football team id). Do not edit by hand.\n" +
    "export const CREST_COLORS = {" + ids.map(id => `${id}:"${out[id]}"`).join(",") + "};\n");
  return ids.length;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) console.log(writeCrestColors(), "crest colours");
