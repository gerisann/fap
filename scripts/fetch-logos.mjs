// Club crests from API-Football's media server (no key, no daily quota) -> web/public/logos/<id>.png (64 px),
// served from our own hosting so visitors' browsers never call a third party. Only missing files are fetched.
// National teams are skipped (federation crests; the app shows the team colour for them).
// Writes web/src/data/logos.js: the ids that have a file, so the app never asks for a crest that is not there.
// Needs ImageMagick (`magick` or `convert`). Run: node scripts/fetch-logos.mjs
import { mkdirSync, existsSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { API_TEAMS, API_IDS } from "../web/src/data/teams-api.js";
import { TEAMS } from "../web/src/data/teams.js";
import { writeCrestColors } from "./crest-colors.mjs";

const OUT = "web/public/logos", PACE_MS = Number(process.env.PACE_MS || 120);
// crests we must not show (a club asked us to take it down): API ids
const BLOCK = new Set([]);

const im = ["magick", "convert"].find(c => { try { execFileSync(c, ["-version"], { stdio: "ignore" }); return true; } catch (_) { return false; } });
if (!im) { console.error("ImageMagick not found"); process.exit(1); }

const national = new Set(TEAMS.filter(t => t[1] === "NAT").map(t => t[0]));
const ids = new Set([
  ...Object.entries(API_IDS).filter(([n]) => !national.has(n)).map(([, id]) => id),
  ...API_TEAMS.filter(t => t[1] !== "NAT").map(t => t[2]),
].filter(id => Number.isInteger(id) && !BLOCK.has(id)));

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (BLOCK.has(Number(f.split(".")[0]))) rmSync(join(OUT, f));

const sleep = ms => new Promise(r => setTimeout(r, ms));
let got = 0, failed = 0;
for (const id of ids) {
  const file = join(OUT, `${id}.png`);
  if (existsSync(file)) continue;
  await sleep(PACE_MS);
  try {
    const r = await fetch(`https://media.api-sports.io/football/teams/${id}.png`);
    if (!r.ok || !(r.headers.get("content-type") || "").startsWith("image/")) throw new Error(`HTTP ${r.status}`);
    const tmp = join(tmpdir(), `crest-${id}.png`);
    writeFileSync(tmp, Buffer.from(await r.arrayBuffer()));
    // 64 px inside a square, transparent padding, small png
    execFileSync(im, [tmp, "-resize", "64x64", "-background", "none", "-gravity", "center", "-extent", "64x64", "-strip", "-define", "png:compression-level=9", "PNG32:" + file]);
    rmSync(tmp); got++;
  } catch (e) { failed++; console.warn(`${id}: ${e.message}`); }
}

const have = [...ids].filter(id => existsSync(join(OUT, `${id}.png`))).sort((a, b) => a - b);
writeFileSync("web/src/data/logos.js",
  "// Generated by scripts/fetch-logos.mjs: API-Football team ids that have a crest in web/public/logos/. Do not edit by hand.\n" +
  `export const LOGOS = new Set(${JSON.stringify(have)});\n`);
console.log(`${got} new, ${failed} failed, ${have.length}/${ids.size} crests, ${writeCrestColors()} crest colours`);
